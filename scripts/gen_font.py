#!/usr/bin/env python3
"""Generate the native anti-aliased font table used by the L2 renderer.

The generated file is included by app/src/main.native.cpp.  Glyphs are kept at
45 device pixels with 8-bit coverage, then sampled by the native renderer at
the current UI density.  This avoids the blocky nearest-neighbour scaling of
the old 7x15 one-bit ASCII table.

Usage:
    python3 scripts/gen_font.py /path/to/Roboto-Regular.ttf > app/src/font_table.inc
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_SIZE = 45
DESIGN_RATIO = 3  # 45 raster pixels map to 15 design units at density 3.
FALLBACK_FONTS = (
    "/system/fonts/Roboto-Regular.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf",
)


def find_font(explicit: str | None) -> Path:
    candidates = []
    if explicit:
        candidates.append(Path(explicit))
    candidates.extend(Path(path) for path in FALLBACK_FONTS)
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise SystemExit("font not found; pass a TTF path explicitly")


def codepoints() -> list[int]:
    # ASCII, Latin-1 supplement, and punctuation commonly used by the UI.
    values = list(range(32, 127))
    values.extend(range(160, 256))
    values.extend((0x00A0, 0x2013, 0x2014, 0x2018, 0x2019,
                   0x201C, 0x201D, 0x2022, 0x2026, 0x2190,
                   0x2192, 0x2212, 0x2713))
    return sorted(set(values))


def raster_glyph(font: ImageFont.FreeTypeFont, codepoint: int):
    char = chr(codepoint)
    try:
        bbox = font.getbbox(char, anchor="ls")
    except (AttributeError, TypeError):
        bbox = font.getbbox(char)
    advance = font.getlength(char)
    if bbox is None:
        return b"", 0, 0, 0, 0, advance

    x0, y0, x1, y1 = bbox
    width = max(0, x1 - x0)
    height = max(0, y1 - y0)
    if width == 0 or height == 0:
        return b"", 0, 0, x0, y0, advance

    image = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(image)
    try:
        draw.text((-x0, -y0), char, font=font, fill=255, anchor="ls")
    except (AttributeError, TypeError):
        draw.text((-x0, -y0), char, font=font, fill=255)
    return image.tobytes(), width, height, x0, y0, advance


def q4(value: float) -> int:
    return int(round(value * 16.0))


def main() -> None:
    font_path = find_font(sys.argv[1] if len(sys.argv) > 1 else None)
    font = ImageFont.truetype(str(font_path), FONT_SIZE)

    glyph_rows: list[tuple[int, int, int, int, int, int]] = []
    pixel_rows: list[bytes] = []
    codepoint_rows: list[tuple[int, int]] = []
    pixel_offset = 0

    for codepoint in codepoints():
        bitmap, width, height, left, top, advance = raster_glyph(font, codepoint)
        glyph_index = len(glyph_rows)
        glyph_rows.append((pixel_offset, width, height, q4(left), q4(top), q4(advance)))
        codepoint_rows.append((codepoint, glyph_index))
        if bitmap:
            pixel_rows.append(bitmap)
            pixel_offset += width * height

    print("// Generated by scripts/gen_font.py; do not edit by hand.")
    print(f"// Source: {font_path.name}; raster size: {FONT_SIZE}px; design ratio: {DESIGN_RATIO}.")
    print("static const FontGlyph kFontGlyphs[] = {")
    for offset, width, height, left, top, advance in glyph_rows:
        print(f"    {{{offset},{width},{height},{left},{top},{advance}}},")
    print("};")
    print(f"static const uint32_t kFontGlyphCount = {len(glyph_rows)};")
    print("static const uint32_t kFontCodepointPairs[] = {")
    for codepoint, glyph_index in codepoint_rows:
        print(f"    0x{codepoint:04X}u,{glyph_index}u,")
    print("};")
    print(f"static const uint32_t kFontCodepointPairCount = {len(codepoint_rows)};")
    print("static const uint8_t kFontPixels[] = {")
    for bitmap in pixel_rows:
        for start in range(0, len(bitmap), 24):
            chunk = bitmap[start:start + 24]
            print("    " + ",".join(str(value) for value in chunk) + ",")
    print("};")


if __name__ == "__main__":
    main()
