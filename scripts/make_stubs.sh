#!/data/data/com.termux/files/usr/bin/bash
# Build link-time STUBS for the Android system libraries we use.
#
# Why: Termux's $PREFIX/lib/libandroid.so is a *wrapper* that depends on
# libtermux-platform-ns.so, which only exists inside Termux. Linking against it
# bakes that dependency into libnbt.so and the app dies at load time on a real
# device. The NDK's own libandroid.so/libz.so/liblog.so are stubs with the
# correct SONAMEs; at run time the device's real libraries satisfy them.
#
# These stubs are used ONLY at link time and are never packaged into the APK.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$HERE/build/stubs"
mkdir -p "$OUT"

gen() { # $1 = soname, $2 = output file, rest = symbols
  local soname="$1" file="$2"; shift 2
  local src="$OUT/stub_$1.c"
  {
    echo "/* generated by scripts/make_stubs.sh - link-time stub for $soname */"
    for s in "$@"; do echo "long $s(void) { return 0; }"; done
  } > "$src"
  clang --target=aarch64-linux-android26 -shared -fPIC -nostdlib \
        -Wl,-soname,"$soname" -o "$file" "$src"
  echo "stub: $file (soname=$soname, $(wc -l < "$src") lines)"
}

gen libandroid.so "$OUT/libandroid.so" \
  AInputQueue_attachLooper AInputQueue_detachLooper AInputQueue_finishEvent AInputQueue_getEvent \
  ALooper_acquire ALooper_forThread ALooper_pollOnce ALooper_release ALooper_wake \
  AMotionEvent_getAction AMotionEvent_getEventTime AMotionEvent_getX AMotionEvent_getY \
  ANativeWindow_getHeight ANativeWindow_getWidth ANativeWindow_lock \
  ANativeWindow_setBuffersGeometry ANativeWindow_unlockAndPost

gen libz.so "$OUT/libz.so" compress2 compressBound crc32 inflate inflateEnd inflateInit2_

gen liblog.so "$OUT/liblog.so" __android_log_print

echo "== verify sonames =="
for f in "$OUT"/libandroid.so "$OUT"/libz.so "$OUT"/liblog.so; do
  printf '%s -> ' "$(basename "$f")"; readelf -d "$f" | awk '/SONAME/{print $NF}'
done
